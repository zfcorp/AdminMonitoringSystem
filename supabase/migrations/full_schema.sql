-- ─── Helper: updated_at trigger function ─────────────────────

CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;


-- ============================================================
-- BRANCHES (already exists — just ensure constraint + RLS)
-- ============================================================

CREATE TABLE IF NOT EXISTS branches (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.table_constraints
    WHERE table_schema = 'public'
      AND table_name   = 'branches'
      AND constraint_type = 'UNIQUE'
      AND constraint_name = 'branches_name_key'
  ) THEN
    ALTER TABLE branches ADD CONSTRAINT branches_name_key UNIQUE (name);
  END IF;
END $$;

DROP TRIGGER IF EXISTS branches_set_updated_at ON branches;
CREATE TRIGGER branches_set_updated_at
  BEFORE UPDATE ON branches
  FOR EACH ROW EXECUTE FUNCTION update_updated_at();

ALTER TABLE branches ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "branches_all" ON branches;
CREATE POLICY "branches_all" ON branches
  FOR ALL TO authenticated USING (true) WITH CHECK (true);


